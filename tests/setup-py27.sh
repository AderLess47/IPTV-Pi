#!/bin/sh
#
# IPTV-Pi: build a self-contained Python 2.7 for the "verify-py27" job.
#
#     ./tests/setup-py27.sh
#
# The image ships Python 2.7 (Kodi 18 brings it along), but a normal Linux
# workstation usually has none, and Docker is not always available either.
# This script assembles a throwaway 2.7 from Debian buster packages — the same
# 2.7.16 the suites were tested against — into a directory that survives a
# reboot of /tmp, installs exactly the Flask pins the CI job uses and leaves a
# `python2.7` wrapper behind. tests/run-py27.sh picks it up automatically.
#
# Default target: $HOME/.cache/iptvpi-py27  (override: IPTV_PY27_PREFIX=...)
# Nothing outside that directory is touched; no root, no apt-get, no Docker.

set -eu

PREFIX=${IPTV_PY27_PREFIX:-$HOME/.cache/iptvpi-py27}
WRAPPER=$PREFIX/bin/python2.7
SUITE_URL=https://archive.debian.org/debian
INDEX_URL=$SUITE_URL/dists/buster/main/binary-amd64/Packages.gz
GETPIP_URL=https://bootstrap.pypa.io/pip/2.7/get-pip.py
PINS="flask==1.1.4 werkzeug==1.0.1 jinja2==2.11.3 markupsafe==1.1.1 itsdangerous==1.1.0 click==7.1.2"

# python2.7 itself, the standard library and the two libraries pip needs for
# TLS: buster linked against libssl1.1 and libffi6, which Ubuntu 24.04 does not
# ship any more.
PACKAGES="python2.7-minimal libpython2.7-minimal libpython2.7-stdlib
          python2.7 libpython2.7 libssl1.1 libffi6"

say() { printf '>>> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

if [ -x "$WRAPPER" ] && "$WRAPPER" -c 'import flask' >/dev/null 2>&1; then
    say "Python 2.7 is already set up: $WRAPPER"
    "$WRAPPER" -V 2>&1
    exit 0
fi

command -v curl >/dev/null 2>&1 || die "curl is needed"
command -v dpkg-deb >/dev/null 2>&1 || die "dpkg-deb is needed (Debian/Ubuntu host)"

case $(dpkg --print-architecture 2>/dev/null || echo unknown) in
    amd64) ;;
    *) die "this script only assembles the amd64 packages; on other hosts use Docker or a python2.7 from the distribution" ;;
esac

WORK=$(mktemp -d) || die "no temporary directory"
trap 'rm -rf "$WORK"' EXIT INT TERM

say "fetching the buster package index"
curl -fsSL --max-time 120 -o "$WORK/Packages.gz" "$INDEX_URL" \
    || die "could not download $INDEX_URL"
gzip -dc "$WORK/Packages.gz" > "$WORK/Packages"

# Print the download path of a package as listed in the index.
deb_path() {
    awk -v wanted="$1" '
        /^Package: / { hit = (substr($0, 10) == wanted); next }
        hit && /^Filename: / { print substr($0, 11); exit }
    ' "$WORK/Packages"
}

mkdir -p "$PREFIX"
for package in $PACKAGES; do
    path=$(deb_path "$package")
    [ -n "$path" ] || die "package $package is not in the buster index"
    say "unpacking $package"
    curl -fsSL --max-time 180 -o "$WORK/$package.deb" "$SUITE_URL/$path" \
        || die "could not download $path"
    dpkg-deb -x "$WORK/$package.deb" "$PREFIX" || die "could not unpack $package"
done

mkdir -p "$PREFIX/bin"
cat > "$WRAPPER" <<EOF
#!/bin/sh
# Generated by tests/setup-py27.sh: a Python 2.7 with the CI Flask pins.
PREFIX=\$(cd "\$(dirname "\$0")/.." && pwd)
PYTHONHOME="\$PREFIX/usr"
LD_LIBRARY_PATH="\$PREFIX/usr/lib/x86_64-linux-gnu\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export PYTHONHOME LD_LIBRARY_PATH
exec "\$PREFIX/usr/bin/python2.7" "\$@"
EOF
chmod +x "$WRAPPER"

say "checking the interpreter"
"$WRAPPER" -V 2>&1 || die "the unpacked interpreter does not start"
"$WRAPPER" -c 'import ssl' || die "ssl is missing; pip cannot reach the network"

say "installing the CI pins"
curl -fsSL --max-time 120 -o "$WORK/get-pip.py" "$GETPIP_URL" \
    || die "could not download get-pip.py"
"$WRAPPER" "$WORK/get-pip.py" --no-warn-script-location >"$WORK/pip.log" 2>&1 \
    || { cat "$WORK/pip.log" >&2; die "could not bootstrap pip"; }
# --target puts the pins where Debian's python looks: dist-packages, which is
# always on sys.path, unlike site-packages.
"$WRAPPER" -m pip install -q --no-cache-dir \
    --target "$PREFIX/usr/lib/python2.7/dist-packages" $PINS \
    || die "could not install the Flask pins"

"$WRAPPER" -c 'import flask, jinja2, werkzeug; print("flask %s, jinja2 %s, werkzeug %s" % (flask.__version__, jinja2.__version__, werkzeug.__version__))' \
    || die "the pins are not importable"

say "Python 2.7 ready: $WRAPPER"
say "tests/run-py27.sh and tests/run-checks.sh use it automatically"
